// BCIB worker state (validation profile only)
static proc_t *g_bcib_worker = NULL;
static uint64_t g_bcib_worker_pid = 0;

// USER worker state (validation profile only)
static proc_t *g_user_worker = NULL;
static uint64_t g_user_worker_pid = 0;

// BCIB worker entry point (external assembly)
extern void bcib_worker_entry(void);

// Dual-channel debug output
static void bcib_debug(const char *msg) {
    if (!msg) return;
    while (*msg) {
        outb(0xE9, (uint8_t)*msg);
        outb(0x3F8, (uint8_t)*msg);
        msg++;
    }
}

/**
 * bcib_worker_create - Create BCIB worker process (validation profile only)
 * 
 * Creates a dedicated BCIB-role process during kernel initialization.
 * This worker can call SYS_V2_SUBMIT_EXECUTION without enforcement violation.
 * 
 * Acceptance Criteria:
 *   - Worker process created with deterministic PID
 *   - Process has PROC_EXECUTION_ROLE_BCIB from creation
 *   - Worker has inbox/payload regions mapped
 *   - Worker can call SYS_V2_SUBMIT_EXECUTION without kill
 * 
 * Returns:
 *   0 on success, -1 on failure
 */
int bcib_worker_create(void) {
    bcib_debug("[[AYKEN_BCIB_WORKER_CREATE_BEGIN]]\n");
    
    // Guard: Only create once
    if (g_bcib_worker != NULL) {
        bcib_debug("[[AYKEN_BCIB_WORKER_CREATE_SKIP]] already_created\n");
        return 0;
    }
    
    // Create BCIB worker process with actual BCIB worker payload
    // In dual-payload mode, use embedded_elf_bcib; otherwise use embedded_elf (legacy)
    // Symbols are generated by tools/embed_elf.py and defined in kernel/include/embedded_elf.h
#ifdef embedded_elf_bcib
    const uint8_t *image = embedded_elf_bcib;
    uint64_t image_size = (uint64_t)embedded_elf_bcib_size;
#else
    const uint8_t *image = embedded_elf;
    uint64_t image_size = (uint64_t)embedded_elf_size;
#endif
    
    // Create user process with BCIB worker name
    proc_t *worker = proc_create_user_process("bcib_worker", image, image_size, PROC_IMAGE_ELF);
    
    if (worker == NULL) {
        bcib_debug("[[AYKEN_BCIB_WORKER_CREATE_FAIL]] proc_create_failed\n");
        return -1;
    }
    
    // CRITICAL: Assign BCIB execution role
    // This is the kernel-authoritative role assignment that enables
    // the worker to call SYS_V2_SUBMIT_EXECUTION without enforcement violation
    worker->execution_role = PROC_EXECUTION_ROLE_BCIB;
    
    // Store worker reference
    g_bcib_worker = worker;
    g_bcib_worker_pid = (uint64_t)worker->pid;
    
    // Emit success marker with PID and role
    bcib_debug("[[AYKEN_BCIB_WORKER_CREATE_OK]] pid=");
    
    // Emit PID as decimal digits
    uint64_t pid = g_bcib_worker_pid;
    if (pid == 0) {
        outb(0xE9, '0');
        outb(0x3F8, '0');
    } else {
        char digits[20];
        int i = 0;
        while (pid > 0) {
            digits[i++] = '0' + (pid % 10);
            pid /= 10;
        }
        // Reverse digits
        for (int j = i - 1; j >= 0; j--) {
            outb(0xE9, (uint8_t)digits[j]);
            outb(0x3F8, (uint8_t)digits[j]);
        }
    }
    
    bcib_debug(" role=BCIB\n");
    
    return 0;
}

